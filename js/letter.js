const TRACK = 0.17;
const glyphOf = ch => GLYPHS[ch] || GLYPHS[ch.toUpperCase()] || GLYPHS[' '];
const textW = (text, size) => {
  let w = 0;
  for (const ch of text) w += (glyphOf(ch)[0] + TRACK) * size;
  return w - TRACK * size;
};

// A line of it. The baseline drifts, the size wanders, and one or two letters
// got leaned on harder than the rest — which is all that separates writing from
// setting type.
function lettering(R, text, x, y, size, o = {}) {
  const a = o.alpha ?? rr(R, 0.62, 0.86);
  const w = (o.w ?? 0.09) * size;
  const drift = o.drift ?? size * 0.055;
  const ph = rr(R, 0, TAU);
  const slant = o.slant ?? rr(R, -0.04, 0.04);
  let cx = x;
  let i = 0;
  for (const ch of text) {
    const [gw, strokes] = glyphOf(ch);
    const t = i / Math.max(1, text.length - 1);
    const dy = Math.sin(t * 3.4 + ph) * drift + rr(R, -0.4, 0.4);
    const sz = size * rr(R, 0.96, 1.05);
    const ga = a * rr(R, 0.78, 1.15);
    for (const st of strokes) {
      const pts = st.map(p => {
        const px = p[0] * sz, py = (p[1] - 1) * sz;
        return [cx + px - py * slant, y + py + dy];
      });
      ink(R, pts, w * rr(R, 0.85, 1.2), {
        alpha: Math.min(1, ga), amp: size * 0.02 + 0.3, over: size * rr(R, 0.01, 0.05),
        skip: 1, taper: 0.14, nib: chance(R, 0.3)
      });
    }
    cx += (gw + TRACK) * size;
    i++;
  }
  return cx - x;
}

// A note with a line pointing at the thing it is about.
function annotate(R, text, x, y, size, target, o = {}) {
  const w = lettering(R, text, x, y, size, o);
  if (!target) return w;
  const from = [x + (o.fromRight ? w + size * 0.3 : -size * 0.3), y - size * 0.35];
  const mid = [lerp(from[0], target[0], 0.55) + rr(R, -size, size),
               lerp(from[1], target[1], 0.55) + rr(R, -size, size)];
  ink(R, chaikin([from, mid, target], false, 2), size * 0.055,
    { alpha: rr(R, 0.3, 0.5), amp: 0.9, skip: 1.2, taper: 0.2, nib: false });
  // a small arrowhead, drawn as two flicks
  const a = Math.atan2(target[1] - mid[1], target[0] - mid[0]);
  const hl = size * 0.32;
  for (const s of [0.5, -0.5]) {
    ink(R, [target, [target[0] - Math.cos(a + s) * hl, target[1] - Math.sin(a + s) * hl]],
      size * 0.05, { alpha: rr(R, 0.35, 0.55), amp: 0.4, skip: 0, taper: 0.25, nib: false });
  }
  return w;
}

